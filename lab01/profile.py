try:
    surname = input("Введите фамилию: ")
    name = input("Введите имя: ")
    group = input("Введите группу: ")
    city = input("Введите город: ")
    age = int(input("Введите возраст в полных годах: "))
    fav_pred = input("Введите любимый предмет: ")
    study_hours = float(input("Введите кол-во часов подготовки в неделю: "))

    if study_hours < 0 or age < 1 or age > 120:
        print("Возраст должен быть от 1 до 120 лет, а часы подготовки — неотрицательным числом")
    else:
        print("\n-*-*-*-*-*-*-*-*-*-*-*-")
        print("Карточка студента:")
        print(f"\nИмя Фамилия: {name} {surname}")
        print(f"Группа: {group}")
        print(f"Город: {city}")
        print(f"Любимый предмет: {fav_pred}")
        print(f"Возраст через 4 года: {age + 4}")
        print(f"Время подготовки за 4 недели: {study_hours * 4:.2f} часов")
        print(f"Среднее время подготовки в день за 7 дней: {study_hours / 7:.2f} часов")
        print("-*-*-*-*-*-*-*-*-*-*-*-")

except ValueError:
    print("Возраст должен быть целым числом, а часы подготовки - числом")